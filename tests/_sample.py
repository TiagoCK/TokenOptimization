"""Shared by the sample-report generator and its regression test.

The committed examples/sample-report.md must be reproducible, so the date is
pinned -- otherwise the file would differ on every run and the test would be
useless.
"""

from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "examples" / "sample-report.md"
GENERATED_AT = datetime(2026, 9, 10, tzinfo=timezone.utc)

PREAMBLE = """<!-- Generated by: python -m tests.generate_sample -->
> **This is a sample.** It was produced from the synthetic fixtures in
> `tests/fixtures/`, not from anyone's real usage data. The numbers are chosen
> to exercise every check; they are not typical of any organisation.

"""


def build() -> str:
    from claude_spend_audit import __version__
    from claude_spend_audit.checks import CheckConfig, run_checks
    from claude_spend_audit.frame import merge
    from claude_spend_audit.ingest import load_cost_csv, load_usage_csv
    from claude_spend_audit.ingest.schema import Profile
    from claude_spend_audit.pricing import PricingTable
    from claude_spend_audit.render import markdown
    from claude_spend_audit import gaps as gapmod

    pricing = PricingTable.load(ROOT / "pricing" / "2026-09.json")
    usage_profile = Profile.load(ROOT / "schemas" / "console_usage_csv.json")
    cost_profile = Profile.load(ROOT / "schemas" / "console_cost_csv.json")

    fixtures = ROOT / "tests" / "fixtures" / "csv"
    usage, _ = load_usage_csv(fixtures / "usage_console.csv", usage_profile)
    cost, _ = load_cost_csv(fixtures / "cost_console.csv", cost_profile)
    frame = merge(usage, cost)

    estimate = pricing.estimate_frame(frame)
    frame = frame.with_gaps(estimate.gaps)
    run = run_checks(frame, pricing, CheckConfig())
    frame = frame.with_gaps(run.gaps)

    body = markdown.render(
        frame,
        pricing,
        estimate,
        run.findings,
        skipped=run.skipped,
        version=__version__,
        generated_at=GENERATED_AT,
    )
    # Paths differ per machine; keep the committed sample stable.
    body = body.replace(str(ROOT) + "\\", "").replace(str(ROOT) + "/", "")
    return PREAMBLE + body
